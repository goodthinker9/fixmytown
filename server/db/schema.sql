-- =====================================================================
-- FixMyTown - Database Schema (Phase 1)
-- Run this entire script in the Supabase SQL Editor.
-- Safe to re-run: it drops existing objects first so you get a clean slate.
-- =====================================================================

-- pgcrypto gives us gen_random_uuid() (built into PG13+ core, but the
-- extension guarantees portability across Supabase environments).
create extension if not exists pgcrypto;

-- ---------------------------------------------------------------------
-- ENUM TYPES
-- We use Postgres enums instead of CHECK constraints because the set of
-- allowed values is small, fixed, and reused across columns/tables. Enums
-- enforce integrity at the type level, are storage-efficient, and make the
-- schema self-documenting. Trade-off: adding a value later needs ALTER TYPE.
-- ---------------------------------------------------------------------
create type user_role        as enum ('resident', 'admin');
create type report_category  as enum ('water', 'electricity', 'roads', 'garbage', 'safety', 'other');
create type report_status    as enum ('reported', 'in_progress', 'resolved');
create type report_priority  as enum ('low', 'medium', 'high');

-- ---------------------------------------------------------------------
-- USERS
-- id: UUID primary key, generated by the DB (not the app) so we avoid
--     ID-enumeration attacks and stay aligned with Supabase auth patterns.
-- password_hash: stored as text because we hash with bcrypt in Node, so the
--     DB never sees a plaintext password.
-- role: defaults to 'resident'; an admin is created by flipping this value.
-- ---------------------------------------------------------------------
create table users (
    id            uuid primary key default gen_random_uuid(),
    name          text not null,
    email         text not null unique,
    password_hash text not null,
    role          user_role not null default 'resident',
    created_at    timestamptz not null default now()
);

-- ---------------------------------------------------------------------
-- REPORTS
-- upvote_count: a DENORMALIZED counter. Storing it here lets us list
--   reports sorted by popularity without running COUNT(*) on upvotes for
--   every row. We keep it in sync from the application layer (and could
--   alternatively use a trigger). Default 0 so a new report starts clean.
-- updated_at: auto-maintained by the trigger below.
-- resolved_at: set when status becomes 'resolved'; nullable otherwise.
-- latitude/longitude: validated to valid geographic ranges.
-- ---------------------------------------------------------------------
create table reports (
    id            uuid primary key default gen_random_uuid(),
    user_id       uuid not null references users(id) on delete cascade,
    title         text not null,
    description   text not null,
    category      report_category not null,
    status        report_status not null default 'reported',
    latitude      double precision not null check (latitude  between -90 and 90),
    longitude     double precision not null check (longitude between -180 and 180),
    image_url     text,
    priority      report_priority not null default 'medium',
    upvote_count  integer not null default 0,
    created_at    timestamptz not null default now(),
    updated_at    timestamptz not null default now(),
    resolved_at   timestamptz
);

-- ---------------------------------------------------------------------
-- UPVOTES
-- Composite primary key (user_id, report_id) guarantees a user can upvote
-- a given report exactly once. No extra unique constraint needed.
-- ON DELETE CASCADE on both FKs means deleting a user or a report cleans up
-- their upvotes automatically.
-- ---------------------------------------------------------------------
create table upvotes (
    user_id    uuid not null references users(id)    on delete cascade,
    report_id  uuid not null references reports(id)  on delete cascade,
    created_at timestamptz not null default now(),
    primary key (user_id, report_id)
);

-- ---------------------------------------------------------------------
-- STATUS HISTORY
-- Tracks every status transition for a report (audit trail).
-- old_status nullable: the very first transition has no previous status.
-- changed_by ON DELETE SET NULL: if an admin account is deleted we keep the
-- history record but anonymize who made the change (preserve the audit trail).
-- ---------------------------------------------------------------------
create table status_history (
    id          uuid primary key default gen_random_uuid(),
    report_id   uuid not null references reports(id) on delete cascade,
    old_status  report_status,
    new_status  report_status not null,
    note        text,
    changed_by  uuid references users(id) on delete set null,
    created_at  timestamptz not null default now()
);

-- ---------------------------------------------------------------------
-- INDEXES
-- Speed up the common queries: filtering reports by status/category and
-- listing newest-first. upvotes.report_id index helps counting/looking up
-- who upvoted a report. status_history.report_id helps the report timeline.
-- ---------------------------------------------------------------------
create index idx_reports_status      on reports(status);
create index idx_reports_category    on reports(category);
create index idx_reports_created_at  on reports(created_at desc);
create index idx_upvotes_report_id   on upvotes(report_id);
create index idx_status_history_report_id on status_history(report_id);

-- ---------------------------------------------------------------------
-- TRIGGER: auto-update reports.updated_at on every UPDATE
-- Centralizing this in a trigger means app code never has to set it by hand
-- and updated_at can never drift out of sync.
-- ---------------------------------------------------------------------
create or replace function update_updated_at()
returns trigger as $$
begin
    new.updated_at = now();
    return new;
end;
$$ language plpgsql;

create trigger trg_reports_updated_at
    before update on reports
    for each row execute function update_updated_at();

